### Recommandation System 

## Types of Recommandation System
## 1)  Popularity Based Recommandation System
## 2)  Content Based Recommandation System
## 3) Collabrative Filtered Based Recommandation System
## 4)  Hybrid Recommandation System


## Popularity-Based Recommendation: Recommends popular movies based on ratings, reviews, views, or overall popularity.
## Content-Based Recommendation: Recommends movies similar to what a user has watched or liked, based on movie content and features.
## Collaborative Filtering: Recommends movies based on the preferences and behavior of users with similar tastes.
## Hybrid Recommendation: Combines content-based and collaborative filtering to provide more personalized recommendations.


